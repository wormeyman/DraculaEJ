"""Generate macOS-style Aurorae button SVGs (close, minimize, maximize, restore) in Dracula colours.

Each file holds the five elements Aurorae looks up: active-center, hover-center, pressed-center,
inactive-center and deactivated-center. Every element is a group whose bounds are set by an
invisible 16x16 square, so the circle (radius 7, plus a 0.5 edge) never touches the box edge and
Aurorae scales a square, not a cropped shape.

Usage: python3 make_buttons.py OUT_DIR
"""
import os
import sys

BOX = 16
C = BOX / 2
R = 7.0
EDGE_W = 0.5

# name: (fill, edge, pressed fill, glyph colour)
COLOURS = {
    "close": ("#ff79c6", "#d6539e", "#e25ca9", "#5e1a40"),
    "minimize": ("#ffb86c", "#d4904a", "#e8a052", "#6b3d10"),
    "maximize": ("#50fa7b", "#2fc458", "#3ee06a", "#11552a"),
    "restore": ("#50fa7b", "#2fc458", "#3ee06a", "#11552a"),
}
INACTIVE_FILL, INACTIVE_EDGE = "#5a5c6e", "#4a4c5c"


def glyph(name: str, colour: str) -> str:
    stroke = f'stroke="{colour}" stroke-width="1.4" stroke-linecap="round" fill="none"'
    if name == "close":
        d = 2.4
        return (f'<path d="M{C - d},{C - d} L{C + d},{C + d} M{C + d},{C - d} L{C - d},{C + d}" {stroke}/>')
    if name == "minimize":
        return f'<path d="M{C - 3.2},{C} L{C + 3.2},{C}" {stroke}/>'
    if name == "maximize":
        return f'<path d="M{C - 3.2},{C} L{C + 3.2},{C} M{C},{C - 3.2} L{C},{C + 3.2}" {stroke}/>'
    # restore: two small triangles pointing at each other, like macOS leaving full screen
    return (f'<path d="M{C - 0.6},{C - 0.6} L{C - 0.6},{C - 3.6} L{C - 3.6},{C - 0.6} Z '
            f'M{C + 0.6},{C + 0.6} L{C + 0.6},{C + 3.6} L{C + 3.6},{C + 0.6} Z" fill="{colour}"/>')


def element(elem_id: str, x: float, fill: str, edge: str, inner: str = "", opacity: float = 1.0) -> str:
    return (f'<g id="{elem_id}" transform="translate({x},0)" opacity="{opacity}">'
            f'<rect width="{BOX}" height="{BOX}" fill="#000000" fill-opacity="0"/>'
            f'<circle cx="{C}" cy="{C}" r="{R}" fill="{fill}" stroke="{edge}" stroke-width="{EDGE_W}"/>'
            f'{inner}</g>')


def build(name: str) -> str:
    fill, edge, pressed, glyph_colour = COLOURS[name]
    parts = [
        element("active-center", 0, fill, edge),
        element("hover-center", 20, fill, edge, glyph(name, glyph_colour)),
        element("pressed-center", 40, pressed, edge, glyph(name, glyph_colour)),
        element("inactive-center", 60, INACTIVE_FILL, INACTIVE_EDGE),
        element("deactivated-center", 80, INACTIVE_FILL, INACTIVE_EDGE, opacity=0.5),
    ]
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="96" height="16" viewBox="0 0 96 16">\n'
            f'<!-- DraculaEJ {name} button, generated by make_buttons.py -->\n' + "\n".join(parts) + "\n</svg>\n")


def main() -> None:
    out_dir = sys.argv[1]
    for name in COLOURS:
        path = os.path.join(out_dir, f"{name}.svg")
        with open(path, "w", encoding="utf-8") as f:
            f.write(build(name))
        print("wrote", path)


if __name__ == "__main__":
    main()
